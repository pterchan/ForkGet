//! Generate admitted target objects from the owned manifest, never SQL remapping.

use fg_protocol_common::{ColumnDefault, ReferentialAction, SnapshotManifest, TableManifest};
use sqlparser::{ast::Expr, dialect::MySqlDialect, parser::Parser, tokenizer::Token};

use super::{SnapshotError, inspect};
use crate::native::{Engine, Native};

pub(super) fn literal(value: &str) -> String {
    format!("E'{}'", value.replace('\\', "\\\\").replace('\'', "''"))
}

fn default(engine: Engine, value: &ColumnDefault) -> String {
    match value {
        ColumnDefault::Null => "NULL".to_owned(),
        ColumnDefault::Number(value) => value.clone(),
        ColumnDefault::Text(value) => {
            if engine == Engine::Postgres {
                literal(value)
            } else {
                format!(
                    "_utf8mb4 X'{}'",
                    value
                        .as_bytes()
                        .iter()
                        .map(|byte| format!("{byte:02X}"))
                        .collect::<String>()
                )
            }
        }
        ColumnDefault::Boolean(value) => if *value { "TRUE" } else { "FALSE" }.to_owned(),
        ColumnDefault::CurrentTimestamp => "CURRENT_TIMESTAMP".to_owned(),
        ColumnDefault::CurrentTimestampPrecision(precision) => {
            format!("CURRENT_TIMESTAMP({precision})")
        }
        ColumnDefault::Generated => String::new(),
    }
}

pub(crate) fn table(
    engine: Engine,
    relation: &str,
    table: &TableManifest,
    delta: bool,
) -> Result<String, SnapshotError> {
    let mut fields = Vec::new();
    for column in &table.columns {
        let required = table.primary_key.contains(&column.name) || (!delta && !column.nullable);
        let mut field = format!(
            "{} {}",
            engine.quote(&column.name),
            column.sql_type.native_name(engine.name())
        );
        if let Some(collation) = &column.collation {
            if engine == Engine::Postgres {
                field.push_str(&format!(" COLLATE {}", engine.quote(collation)));
            } else {
                field.push_str(&format!(
                    " CHARACTER SET utf8mb4 COLLATE {}",
                    engine.quote(collation)
                ));
            }
        }
        if required {
            field.push_str(" NOT NULL");
        }
        if !delta && let Some(value) = &column.default {
            if value == &ColumnDefault::Generated {
                field.push_str(if engine == Engine::Postgres {
                    " GENERATED BY DEFAULT AS IDENTITY"
                } else {
                    " AUTO_INCREMENT"
                });
            } else {
                field.push_str(&format!(" DEFAULT {}", default(engine, value)));
            }
        }
        fields.push(field);
    }
    let mut key = table
        .primary_key
        .iter()
        .map(|column| engine.quote(column))
        .collect::<Vec<_>>();
    if delta {
        fields.push("_fg_branch BIGINT NOT NULL CHECK (_fg_branch>0)".to_owned());
        fields.push("_fg_op CHAR(1) NOT NULL CHECK (_fg_op IN ('I','U','D'))".to_owned());
        key.insert(0, "_fg_branch".to_owned());
    }
    let name = if delta || engine != Engine::Postgres {
        String::new()
    } else {
        table
            .primary_key_name
            .as_ref()
            .map(|name| format!("CONSTRAINT {} ", engine.quote(name)))
            .unwrap_or_default()
    };
    fields.push(format!("{name}PRIMARY KEY ({})", key.join(",")));
    Ok(format!(
        "CREATE TABLE {relation} ({}){}",
        fields.join(","),
        if engine == Engine::Postgres {
            ""
        } else {
            " ENGINE=InnoDB"
        }
    ))
}

fn action(value: ReferentialAction) -> &'static str {
    match value {
        ReferentialAction::NoAction => "NO ACTION",
        ReferentialAction::Restrict => "RESTRICT",
        ReferentialAction::Cascade => "CASCADE",
        ReferentialAction::SetNull => "SET NULL",
    }
}

fn check_expression(engine: Engine, expression: &str) -> Result<String, SnapshotError> {
    if engine != Engine::TiDB {
        return Ok(expression.to_owned());
    }
    let invalid = || SnapshotError::Setting("invalid_tidb_check_expression");
    let dialect = MySqlDialect {};
    let mut parser = Parser::new(&dialect)
        .try_with_sql(expression)
        .map_err(|_| invalid())?;
    let parsed = parser.parse_expr().map_err(|_| invalid())?;
    if parser.peek_token().token != Token::EOF {
        return Err(invalid());
    }
    // TiDB SHOW CREATE adds an outer expression wrapper. Reusing the captured
    // AST inside CHECK (...) would add another wrapper on every import. Remove
    // exactly one; keep nested precedence and immutable manifest bytes intact.
    Ok(match parsed {
        Expr::Nested(inner) => inner.to_string(),
        _ => expression.to_owned(),
    })
}

pub(crate) async fn constraints(
    native: &mut Native,
    schema: &str,
    manifest: &SnapshotManifest,
) -> Result<(), SnapshotError> {
    let engine = native.engine();
    for table in &manifest.tables {
        let relation = engine.relation(schema, &table.name);
        for index in &table.indexes {
            let columns = index
                .columns
                .iter()
                .map(|name| engine.quote(name))
                .collect::<Vec<_>>()
                .join(",");
            let sql = if index.is_constraint {
                let timing = if index.deferrable {
                    if index.initially_deferred {
                        " DEFERRABLE INITIALLY DEFERRED"
                    } else {
                        " DEFERRABLE INITIALLY IMMEDIATE"
                    }
                } else {
                    ""
                };
                format!(
                    "ALTER TABLE {relation} ADD CONSTRAINT {} UNIQUE ({columns}){timing}",
                    engine.quote(&index.name)
                )
            } else {
                format!(
                    "CREATE {}INDEX {} ON {relation} ({columns})",
                    if index.unique { "UNIQUE " } else { "" },
                    engine.quote(&index.name)
                )
            };
            inspect::execute(native, &sql).await?;
        }
        for check in &table.checks {
            inspect::validate_check(&check.expression, &table.columns)?;
            let expression = check_expression(engine, &check.expression)?;
            inspect::execute(
                native,
                &format!(
                    "ALTER TABLE {relation} ADD CONSTRAINT {} CHECK ({})",
                    engine.quote(&check.name),
                    expression
                ),
            )
            .await?;
        }
    }
    for table in &manifest.tables {
        for key in &table.foreign_keys {
            let columns = key
                .columns
                .iter()
                .map(|name| engine.quote(name))
                .collect::<Vec<_>>()
                .join(",");
            let references = key
                .referenced_columns
                .iter()
                .map(|name| engine.quote(name))
                .collect::<Vec<_>>()
                .join(",");
            let timing = if key.deferrable {
                if key.initially_deferred {
                    " DEFERRABLE INITIALLY DEFERRED"
                } else {
                    " DEFERRABLE INITIALLY IMMEDIATE"
                }
            } else {
                ""
            };
            inspect::execute(native,&format!("ALTER TABLE {} ADD CONSTRAINT {} FOREIGN KEY ({columns}) REFERENCES {} ({references}) ON UPDATE {} ON DELETE {}{timing}",engine.relation(schema,&table.name),engine.quote(&key.name),engine.relation(schema,&key.referenced_table),action(key.on_update),action(key.on_delete))).await?;
        }
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn tidb_check_rendering_consumes_exactly_one_captured_wrapper() -> Result<(), SnapshotError> {
        assert_eq!(
            check_expression(Engine::TiDB, "(`amount` >= 0)")?,
            "`amount` >= 0"
        );
        assert_eq!(
            check_expression(Engine::TiDB, "(((`amount` >= 0)))")?,
            "((`amount` >= 0))"
        );
        let unwrapped = " `amount`>= 0 ";
        assert_eq!(check_expression(Engine::TiDB, unwrapped)?, unwrapped);
        Ok(())
    }

    #[test]
    fn tidb_check_rendering_preserves_inner_precedence_and_literals() -> Result<(), SnapshotError> {
        for (captured, rendered) in [
            ("((`amount` + 1) * 2 > 0)", "(`amount` + 1) * 2 > 0"),
            (
                "(`a` > 0 AND (`b` > 0 OR `c` > 0))",
                "`a` > 0 AND (`b` > 0 OR `c` > 0)",
            ),
            ("(`note` = '(literal)')", "`note` = '(literal)'"),
        ] {
            assert_eq!(check_expression(Engine::TiDB, captured)?, rendered);
        }
        assert_ne!(
            check_expression(Engine::TiDB, "((`amount` + 1) * 2 > 0)")?,
            check_expression(Engine::TiDB, "(`amount` + 1 * 2 > 0)")?
        );
        assert_ne!(
            check_expression(Engine::TiDB, "(`amount` >= 0)")?,
            check_expression(Engine::TiDB, "(`amount` > 0)")?
        );
        Ok(())
    }

    #[test]
    fn other_engines_keep_exact_captured_check_text() -> Result<(), SnapshotError> {
        let expression = "((amount >= 0))";
        for engine in [Engine::MySql, Engine::Postgres] {
            assert_eq!(check_expression(engine, expression)?, expression);
        }
        Ok(())
    }

    #[test]
    fn tidb_check_rendering_rejects_invalid_or_trailing_sql() {
        for expression in [
            "(",
            "(`amount` >=)",
            "(`amount` >= 0); SELECT 1",
            "(`amount` >= 0) trailing",
        ] {
            assert!(matches!(
                check_expression(Engine::TiDB, expression),
                Err(SnapshotError::Setting("invalid_tidb_check_expression"))
            ));
        }
    }
}
