#!/usr/bin/env python3
"""Exercise the documented Compose first use and persistent restart locally."""

import argparse
from datetime import UTC, datetime
import importlib.util
import json
import os
from pathlib import Path
import shutil
import socket
import sys
import tempfile
import traceback

import psycopg

SUITE=Path(__file__).resolve().parent
spec=importlib.util.spec_from_file_location("deployment_snapshot",SUITE.parent / "p7/snapshot_import.py")
snapshot=importlib.util.module_from_spec(spec)
spec.loader.exec_module(snapshot)
from run_p2 import ROOT,Failure,json_file,require,wait_until

PORTS=(15432,8081,8082)


class DeploymentRun(snapshot.SnapshotRun):
    def __init__(self,report,workspace,certs,run_id,image,frontend_port,expected_revision=None):
        super().__init__("postgresql",report,workspace,certs,run_id)
        self.deploy=workspace / "deployment"
        self.deployment_project=run_id+"-persistent"
        self.image=image
        self.frontend_port=frontend_port
        self.deployment_started=False
        self.image_id=None
        self.expected_revision=expected_revision
        self.private_settings={}

    def command(self,label,*arguments,**options):
        return self.call(label,["sh",str(self.deploy / "run.sh"),*arguments],env=self.deploy_env,log=True,timeout=350,**options)

    def deployment_compose(self,label,*arguments,**options):
        return self.call(label,["docker","compose","--env-file",str(self.deploy / "operator.env"),
                                "--file",str(self.deploy / "compose.yaml"),*arguments],
                         env=self.deploy_env,log=True,timeout=350,**options)

    def setup(self):
        for port in (*PORTS,self.frontend_port):
            with socket.socket() as listener:
                try:
                    listener.bind(("127.0.0.1",port))
                except OSError:
                    raise Failure(f"Required local deployment port {port} is occupied; no existing service was changed") from None
        self.image_id=self.call("image-id",["docker","image","inspect",self.image,"--format","{{.Id}}"])
        if self.expected_revision:
            actual=self.call("image-revision",["docker","image","inspect",self.image,"--format",'{{index .Config.Labels "org.opencontainers.image.revision"}}'])
            require(actual==self.expected_revision,"The deployment image does not identify the requested source revision")
        self.start_databases()
        self.native_roles()
        self.native("ALTER ROLE p2_service RENAME TO fg_service; ALTER ROLE p2_gc RENAME TO fg_gc; "
                    "ALTER ROLE p34_branch_admin RENAME TO fg_branch_admin;")
        self.native("CREATE DATABASE deployment_source;")
        self.native("CREATE SCHEMA commerce; CREATE TABLE commerce.tasks (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    "note VARCHAR(64) NOT NULL, done BOOLEAN NOT NULL DEFAULT FALSE); "
                    "INSERT INTO commerce.tasks(note) VALUES('source-row');",database="deployment_source")
        self.deploy.mkdir()
        for name in ("prepare.sh","run.sh","metadata-init.sh"):
            (self.deploy / name).write_text((ROOT / "deploy" / name).read_text(),encoding="utf-8",newline="\n")
        original=(ROOT / "deploy/compose.yaml").read_text()
        image,remaining=original.split("\nx-control-environment:",1)
        require("\n  build:" in image,"The deployment image anchor changed")
        image=image.split("\n  build:",1)[0]
        image=image.replace("name: forkget-local",f"name: {self.deployment_project}").replace("image: forkget:local",f"image: {self.image}")
        (self.deploy / "compose.yaml").write_text(image+"\n\nx-control-environment:"+remaining,encoding="utf-8",newline="\n")
        self.deploy_env=self.base_env.copy()
        self.deploy_env["COMPOSE_PROJECT_NAME"]=self.deployment_project
        self.call("prepare",["sh",str(self.deploy / "prepare.sh")],log=True)
        for line in (self.deploy / "operator.env").read_text().splitlines():
            name,_,value=line.partition("=")
            if value.startswith("'") and value.endswith("'"):
                value=value[1:-1]
            self.private_settings[name]=value
        self.private_settings.update({
            "FG_PG_PORT":str(self.frontend_port),
            "FG_BACKEND_DSN":self.dsn("fg_service",self.secret["service"],self.native_port,"p2_native"),
            "FG_BACKEND_GC_DSN":self.dsn("fg_gc",self.secret["collector"],self.native_port,"p2_native"),
            "FG_BRANCH_ADMIN_DSN":self.dsn("fg_branch_admin",self.secret["branch_admin"],self.native_port,"p2_native"),
            "FG_BACKEND_ADMIN_DSN":self.dsn("postgres",self.secret["native"],self.native_port,"p2_native"),
        })
        for name,value in self.private_settings.items():
            if "PASSWORD" in name or "TOKEN" in name:
                self.secret["deployment-"+name]=value
        self.account=json.loads(self.private_settings["FG_FRONTEND_ACCOUNTS"])[0]
        self.secret["deployment-frontend"]=self.account["password"]
        for value in self.private_settings.values():
            require("'" not in value and "\n" not in value,"Unexpected private fixture setting")
        (self.deploy / "operator.env").write_text("".join(f"{name}='{value}'\n" for name,value in self.private_settings.items()),encoding="utf-8",newline="\n")
        (self.deploy / "operator.env").chmod(0o600)
        shutil.copyfile(self.certs / "backend-ca.pem",self.deploy / "private/backend-ca.pem")
        self.deploy_env |= self.private_settings
        self.deploy_env["FG_SOURCE_DSN"]=self.dsn("postgres",self.secret["native"],self.native_port,"deployment_source")
        self.record("private documented preparation uses a dedicated TLS PostgreSQL source and serving target; required ports were free")

    def operator(self,label,*arguments):
        return json.loads(self.command(label,"operator",*arguments))

    def ready(self):
        wait_until("persistent control readiness",lambda:snapshot.p34.p2.http("GET","http://127.0.0.1:8081/health/ready")[0]==204)
        wait_until("persistent proxy readiness",lambda:snapshot.p34.p2.http("GET","http://127.0.0.1:8082/healthz")[0]==204)

    def branch(self,branch_id):
        status,raw=snapshot.p34.p2.http("GET",f"http://127.0.0.1:8081/v1/branches/{branch_id}",self.private_settings["FG_OWNER_TOKEN"])
        return json.loads(raw) if status==200 else None

    def rows(self,branch,write=False):
        with psycopg.connect(host="127.0.0.1",port=self.frontend_port,dbname=branch["name"],user=self.account["user"],
                             password=self.account["password"],sslmode="verify-full",
                             sslrootcert=self.deploy / "private/frontend-ca.pem",autocommit=True) as connection:
            if write:
                generated=connection.execute("INSERT INTO tasks(note,done) VALUES(%s,%s) RETURNING id",("persistent-write",True)).fetchone()[0]
                require(generated>=1<<62,"Writable branch did not allocate a generated key")
            return connection.execute("SELECT id,note,done FROM tasks ORDER BY id").fetchall()

    def execute(self):
        self.setup()
        self.deployment_started=True
        self.command("initialize","initialize")
        self.deployment_compose("capture","run","--rm","-e","FG_SOURCE_DSN","operator","fg-control","snapshot","capture",
                                "--source-env","FG_SOURCE_DSN","--schema","commerce","--name","commerce-v1","--output","/work/commerce")
        imported=self.operator("import","fg-control","snapshot","import","--input","/work/commerce")
        require(imported["status"]=="active","Compose operator did not activate the native snapshot")
        self.command("up","up")
        self.ready()
        doctor=self.operator("doctor","fg-control","doctor")
        json_file(self.report / "doctor.json",doctor)
        require(doctor["runtime_ok"],"Compose doctor did not confirm readiness")
        self.record("initialize, native capture/import and structured doctor succeed through transient operator containers")
        if self.expected_revision:
            capabilities=self.operator("capabilities","forkget","capabilities")
            require(capabilities["source_revision"]==self.expected_revision,
                    "The running control binary differs from the deployment source label")
        branch=self.operator("fork","forkget","fork","persistent-first","--write")
        wait_until("persistent branch activation",lambda:(self.branch(branch["id"]) or {}).get("status")=="active",seconds=90)
        before=self.rows(branch,write=True)
        require(len(before)==2 and before[0]==(1,"source-row",False) and before[1][1:]==("persistent-write",True),"First-use branch rows differ")
        volumes=self.call("volumes-before",["docker","volume","ls","--quiet","--filter",f"label=com.docker.compose.project={self.deployment_project}"]).splitlines()
        require(len(volumes)>=2,"Persistent deployment did not create its named volumes")
        self.command("down-preserve","down")
        retained=self.call("volumes-retained",["docker","volume","ls","--quiet","--filter",f"label=com.docker.compose.project={self.deployment_project}"]).splitlines()
        require(sorted(retained)==sorted(volumes),"Documented down removed persistent volumes")
        self.command("restart","up")
        self.ready()
        after=self.branch(branch["id"])
        require(after and after["generation_id"]==branch["generation_id"] and after["name"]==branch["name"],"Restart lost branch metadata identity")
        require(self.rows(branch)==before,"Restart lost committed branch data")
        self.record("documented down/up retains named metadata/state/capture volumes, branch identity and committed generated-key rows")
        self.operator("drop","forkget","drop","--id",str(branch["id"]))
        wait_until("persistent branch drop",lambda:(self.branch(branch["id"]) or {}).get("status")=="dropped",seconds=90)
        require(self.native("SELECT count(*) FROM information_schema.schemata WHERE schema_name='fg_b1';")=="0","Dropped first-use branch retained native storage")
        self.record("owner CLI drops the recovered branch and native storage after restart")
        json_file(self.report / "persistence.json",{"branch_id":branch["id"],"generation_id":branch["generation_id"],
                                                   "rows":2,"generated_key":before[1][0],"same_branch":True,"same_rows":True,
                                                   "preserved_volumes":volumes,"dropped":True})

    def cleanup(self):
        try:
            if self.deployment_started:
                self.deployment_compose("deployment-cleanup","--profile","tools","down","--volumes","--remove-orphans","--timeout","5")
                for kind in (["ps","-aq"],["volume","ls","--quiet"]):
                    remaining=self.call("deployment-residuals",["docker",*kind,"--filter",f"label=com.docker.compose.project={self.deployment_project}"])
                    require(not remaining,"Disposable deployment retained owned resources")
                self.deployment_started=False
        finally:
            super().cleanup()


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--image",default="forkget:p10-local")
    parser.add_argument("--frontend-port",type=int,default=5432)
    parser.add_argument("--expected-source-revision")
    parser.add_argument("--report-dir",type=Path,required=True)
    options=parser.parse_args()
    report=options.report_dir.resolve()
    report.mkdir(parents=True,exist_ok=False)
    started=datetime.now(UTC)
    errors=[]
    with tempfile.TemporaryDirectory(prefix="fg-compose-acceptance-") as temporary:
        workspace=Path(temporary)
        certs=workspace / "certs"
        snapshot.p34.p2.build_certs(certs)
        runner=DeploymentRun(report,workspace,certs,f"fgdeployment-{started:%H%M%S}-{os.getpid()}",options.image,options.frontend_port,options.expected_source_revision)
        try:
            runner.execute()
        except Exception as error:
            errors.append(runner.safe(str(error)))
            (report / "error.log").write_text(runner.safe(traceback.format_exc()),encoding="utf-8")
        finally:
            try:
                runner.cleanup()
            except Exception as error:
                errors.append(runner.safe(str(error)))
    revision,state=snapshot.p34.p2.git_state()
    json_file(report / "env.json",{"source_revision":revision,"source_state":state,"started_at":started.isoformat(),
                                  "image":options.image,"image_id":runner.image_id,"frontend_port":options.frontend_port,
                                  "image_scope":"exact revision label verified" if options.expected_source_revision else "prebuilt preparatory image; rebuild exact revision before release"})
    result={"status":"failed" if errors else "passed","checks":runner.cases,"errors":errors,
            "cleaned_up":not runner.compose_started and not runner.deployment_started}
    json_file(report / "report.json",result)
    print(json.dumps(result),flush=True)
    return 1 if errors else 0


if __name__=="__main__":
    raise SystemExit(main())
